"""Turn the pictures in .local/icons/ into the launcher icons in src/UI/Assets/img_icons.c (56x56, RGB565 plus an 8 bit alpha
plane, which LVGL draws as RGB565A8; they sit in flash, not RAM). Needs Pillow. Run from the repository root:

    python tools/make_icons.py

GitHub's mark comes as an SVG, so its single path (absolute M L C Z only) is flattened and filled here, white on transparent.
Add an icon: put the picture in .local/icons/, add a line to ICONS, and declare it in src/UI/Assets/Icons.h."""
import re
import sys
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

SIZE = 56
SS = 8  # supersampling for the SVG
ROOT = Path(__file__).resolve().parent.parent
ICONS = [  # name, file
    ("vscode", "250px-Visual_Studio_Code_1.35_icon.svg.webp"),
    ("github", "GitHub_Invertocat_White.svg"),
    ("trackfy", "trackfy.png"),
    ("stackport", "stackport.svg"),
]
TINT = {"stackport.svg": (0x63, 0x66, 0xF1)}  # a one-colour SVG is drawn white unless it has a colour here


def svg_mask(path: Path) -> Image.Image:
    text = path.read_text(encoding="utf-8")
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    d = re.search(r'<path[^>]*?\sd="([^"]+)"', text, re.S).group(1)
    tokens = re.findall(r"[MLCZ]|-?\d*\.?\d+(?:e-?\d+)?", d)
    scale = SIZE * SS * 0.92 / max(vb[2], vb[3])
    ox = (SIZE * SS - vb[2] * scale) / 2
    oy = (SIZE * SS - vb[3] * scale) / 2
    polys, cur, pos, i = [], [], (0.0, 0.0), 0

    def pt(x, y):
        return (ox + (x - vb[0]) * scale, oy + (y - vb[1]) * scale)

    while i < len(tokens):
        cmd = tokens[i]
        i += 1
        if cmd == "M":
            if cur:
                polys.append(cur)
            pos = (float(tokens[i]), float(tokens[i + 1]))
            i += 2
            cur = [pt(*pos)]
        elif cmd == "L":
            pos = (float(tokens[i]), float(tokens[i + 1]))
            i += 2
            cur.append(pt(*pos))
        elif cmd == "C":
            x1, y1, x2, y2, x, y = (float(t) for t in tokens[i : i + 6])
            i += 6
            for s in range(1, 17):
                t = s / 16
                u = 1 - t
                cur.append(pt(u**3 * pos[0] + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x,
                              u**3 * pos[1] + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y))
            pos = (x, y)
        elif cmd == "Z":
            if cur:
                polys.append(cur)
            cur = []
    if cur:
        polys.append(cur)
    mask = Image.new("L", (SIZE * SS, SIZE * SS), 0)
    for poly in polys:  # even-odd: a sub-path inside another is a hole
        layer = Image.new("L", mask.size, 0)
        ImageDraw.Draw(layer).polygon(poly, fill=255)
        mask = ImageChops.difference(mask, layer)
    return mask.resize((SIZE, SIZE), Image.LANCZOS)


def load(file: str) -> Image.Image:
    path = ROOT / ".local" / "icons" / file
    if path.suffix == ".svg":
        img = Image.new("RGBA", (SIZE, SIZE), TINT.get(file, (255, 255, 255)) + (0,))
        img.putalpha(svg_mask(path))
        return img
    img = Image.open(path).convert("RGBA")
    img.thumbnail((SIZE, SIZE), Image.LANCZOS)
    out = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    out.paste(img, ((SIZE - img.width) // 2, (SIZE - img.height) // 2))
    return out


def emit(name: str, img: Image.Image) -> str:
    color, alpha = bytearray(), bytearray()
    for r, g, b, a in img.getdata():
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        color += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    data = bytes(color + alpha)
    rows = ",\n".join("  " + ",".join(f"0x{b:02x}" for b in data[n : n + 32]) for n in range(0, len(data), 32))
    return f"""static const uint8_t img_icon_{name}_map[] = {{
{rows}
}};

const lv_image_dsc_t img_icon_{name} = {{
  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 2}, .reserved_2 = 0 }},
  .data_size = {len(data)},
  .data = img_icon_{name}_map,
}};
"""


def main() -> int:
    parts = ["// Generated by tools/make_icons.py from .local/icons/. Do not edit.", '#include "lvgl.h"', ""]
    for name, file in ICONS:
        parts.append(emit(name, load(file)))
    (ROOT / "src/UI/Assets/img_icons.c").write_text("\n".join(parts), encoding="utf-8")
    prev = Image.new("RGBA", (SIZE * len(ICONS), SIZE), (30, 36, 44, 255))
    for n, (_, file) in enumerate(ICONS):
        prev.alpha_composite(load(file), (n * SIZE, 0))
    prev.resize((prev.width * 3, prev.height * 3), Image.NEAREST).save(sys.argv[1] if len(sys.argv) > 1 else ROOT / ".local" / "icons_preview.png")
    print("wrote src/UI/Assets/img_icons.c")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
