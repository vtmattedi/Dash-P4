"""Pre-build: (1) say which firmware this env is, (2) write include/Version.h from src/Version/version,
(3) drop a stale sdkconfig.

The version is bumped by editing src/Version/version on purpose; builds never
rewrite it, so a build does not dirty the working tree. Only the (git-ignored)
header and its timestamp change.
"""
import datetime
import os
import re

Import("env")  # noqa: F821  (PlatformIO injects this)

project = env.subst("$PROJECT_DIR")

# --- firmware choice ----------------------------------------------------------------------
# platformio.ini `custom_dash_app` (dashboard | usb_screen | dashboard_usb). CMake reads it from the
# environment: the IDF configure step, and its separate requirement-expansion process, inherit ours.
APPS = ("dashboard", "usb_screen", "dashboard_usb")
dash_app = env.GetProjectOption("custom_dash_app", "dashboard").strip()
if dash_app not in APPS:
    raise SystemExit("custom_dash_app must be one of %s, not %r" % (", ".join(APPS), dash_app))
os.environ["DASH_APP"] = dash_app
# platformio.ini `custom_dash_espnow = yes`: ESP-NOW through the C6 (adds the espnow_hosted component; the
# env also sets -DNM_NETWORK_ESPNOW=1 for the library).
dash_espnow = env.GetProjectOption("custom_dash_espnow", "no").strip().lower() in ("yes", "true", "1")
os.environ["DASH_ESPNOW"] = "1" if dash_espnow else "0"
print("Dash-P4 firmware: %s%s" % (dash_app, " + ESP-NOW over the C6" if dash_espnow else ""))

version_file = os.path.join(project, "src", "Version", "version")
header = os.path.join(project, "include", "Version.h")

try:
    with open(version_file) as f:
        version = f.readline().strip() or "0.0.0"
except OSError:
    version = "0.0.0"

os.makedirs(os.path.dirname(header), exist_ok=True)
with open(header, "w") as f:
    f.write(
        "// AUTO GENERATED by src/Version/script.py, DO NOT EDIT\n"
        "#ifndef VERSION\n#define VERSION \"%s\"\n#endif\n"
        "#ifndef BUILD_TIMESTAMP\n#define BUILD_TIMESTAMP \"%s\"\n#endif\n"
        % (version, datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    )
print("Dash-P4 version %s" % version)

# --- stale sdkconfig ----------------------------------------------------------------------
# PlatformIO merges sdkconfig.defaults into sdkconfig.<env> only when that file is missing, and
# the board's defaults (board/sdkconfig.board) are merged by our root CMakeLists, which
# PlatformIO knows nothing about. An edit to either would silently not take effect -- a bug that
# once shipped an out-of-bounds gradient array. So: if a defaults file is newer than the generated
# sdkconfig, delete the generated one and let it be rebuilt. Only the files this firmware merges
# count (the list mirrors the root CMakeLists.txt).
generated = os.path.join(project, "sdkconfig." + env["PIOENV"])
if os.path.exists(generated):
    sources = [
        os.path.join(project, "sdkconfig.defaults"),
        os.path.join(project, "board", "sdkconfig.board"),
    ]
    if dash_app == "usb_screen":
        sources.append(os.path.join(project, "src", "UsbScreen", "sdkconfig.usb_screen"))
    newest = 0
    for source in sources:
        if os.path.exists(source):
            newest = max(newest, os.path.getmtime(source))
    if newest > os.path.getmtime(generated):
        os.remove(generated)
        print("sdkconfig defaults changed: regenerating sdkconfig.%s" % env["PIOENV"])
